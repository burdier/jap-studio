#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn languages_round_trip_and_cover_core_ui_strings() {
        for lang in Language::ALL {
            assert_eq!(Language::parse(lang.token()), Some(lang));
            assert!(!lang.label().is_empty());
            assert!(!tr(lang, UiText::MenuFile).is_empty());
            assert!(!tr(lang, UiText::SettingsTitle).is_empty());
            assert!(!tr(lang, UiText::ShortcutPresetHeading).is_empty());
        }
        assert_eq!(Language::parse("english"), Some(Language::En));
        assert_eq!(Language::parse("jp"), Some(Language::Ja));
        assert_eq!(Language::parse_profile("THEME=cuaderno\n"), None);
        assert_eq!(
            Language::parse_profile("THEME=cuaderno\nLANGUAGE=pt\n"),
            Some(Language::Pt)
        );
    }
}
